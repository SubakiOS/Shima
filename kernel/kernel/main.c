#include "../arch/x86_64/framebuffer/framebuffer.h"
#include "limine_boot.h"
#include <string.h>



static void hcf(void) {
    for (;;) {
        asm ("hlt");
    }
}

// kern entry pint

void Kmain(void) {

    struct limine_framebuffer *fb = limine_get_framebuffer();

    if  (fb == NULL) {
        hcf();
    }

    fb_pattern(fb);
    hcf();
}